CREATE TABLE IF NOT EXISTS manual.crypto_market_snapshot (
    coin_id VARCHAR(50) NOT NULL,
    symbol VARCHAR(10) NOT NULL,
    name VARCHAR(100) NOT NULL,
    image VARCHAR(255),
    current_price NUMERIC(20, 8) NOT NULL,
    market_cap NUMERIC(20, 2) NOT NULL,
    market_cap_rank INT,
    fully_diluted_valuation NUMERIC(20, 2),
    total_volume NUMERIC(20, 2) NOT NULL,
    high_24h NUMERIC(20, 8),
    low_24h NUMERIC(20, 8),
    price_change_24h NUMERIC(20, 8),
    price_change_percentage_24h NUMERIC(5, 2),
    market_cap_change_24h NUMERIC(20, 2),
    market_cap_change_percentage_24h NUMERIC(5, 2),
    circulating_supply NUMERIC(20, 2),
    total_supply NUMERIC(20, 2),
    max_supply NUMERIC(20, 2),
    ath NUMERIC(20, 8),
    ath_change_percentage NUMERIC(5, 2),
    ath_date TIMESTAMPTZ,
    atl NUMERIC(20, 8),
    atl_change_percentage NUMERIC(5, 2),
    atl_date TIMESTAMPTZ,
    last_updated TIMESTAMPTZ NOT NULL,
    price_eur NUMERIC(20, 8),
    price_gbp NUMERIC(20, 8),
    price_jpy NUMERIC(20, 8),
    price_chf NUMERIC(20, 8),
    price_cad NUMERIC(20, 8),
    sentiment_label VARCHAR(20),
    market_cap_category VARCHAR(20),
    volatility_flag BOOLEAN,
    supply_emission_stage VARCHAR(20),
    weekly_trend VARCHAR(20),
    data_quality_flag INT NOT NULL,
    ath_drawdown_pct NUMERIC(5, 2),
    atl_upside_pct NUMERIC(5, 2),
    mcap_fdv_ratio NUMERIC(20, 8),
    volume_to_mcap_ratio NUMERIC(20, 8),
    supply_ratio NUMERIC(5, 4),
    PRIMARY KEY (coin_id)
);

CREATE INDEX idx_timestamp ON manual.crypto_market_snapshot (last_updated);
CREATE INDEX idx_id ON manual.crypto_market_snapshot (coin_id);
CREATE INDEX idx_category ON manual.crypto_market_snapshot (market_cap_category);